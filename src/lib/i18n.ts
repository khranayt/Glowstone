export const t = (text: string, vars?: Record<string, string | number>): string => {
  let value = currentLanguage === "ru" ? (ru[text] ?? text) : text;
  if (vars) {
    for (const [key, replacement] of Object.entries(vars)) {
      value = value.split(`{${key}}`).join(String(replacement));
    }
  }
  return value;
};

export const plural = (
  n: number,
  forms: { en: [string, string]; ru: [string, string, string] },
): string => {
  if (currentLanguage === "en") return n === 1 ? forms.en[0] : forms.en[1];
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms.ru[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms.ru[1];
  return forms.ru[2];
};
